-- Peek initial schema, PostgreSQL dialect.
--
-- It mirrors migrations/sqlite/0001_init.sql table for table and column for
-- column; only the types differ (BYTEA for BLOB, BIGINT for the unix
-- timestamps, an identity column for the audit sequence). The application SQL
-- is shared, so any divergence here shows up immediately in the tests.

CREATE TABLE organizations (
    id         TEXT PRIMARY KEY,
    slug       TEXT NOT NULL UNIQUE,
    name       TEXT NOT NULL,
    policies   TEXT NOT NULL DEFAULT '{}',
    created_at BIGINT NOT NULL
);

CREATE TABLE secrets (
    id                     TEXT PRIMARY KEY,
    org_id                 TEXT NOT NULL REFERENCES organizations (id),
    creator_id             TEXT,
    kind                   TEXT NOT NULL,
    ciphertext             BYTEA,
    storage_ref            TEXT,
    size_bytes             BIGINT NOT NULL DEFAULT 0,
    read_token_hash        BYTEA NOT NULL,
    receipt_token_hash     BYTEA NOT NULL,
    kdf_salt               BYTEA NOT NULL,
    kdf_memory_kib         BIGINT NOT NULL,
    kdf_iterations         BIGINT NOT NULL,
    kdf_parallelism        BIGINT NOT NULL,
    has_passphrase         INTEGER NOT NULL DEFAULT 0,
    retrieval_step         INTEGER NOT NULL DEFAULT 1,
    deletable_by_recipient INTEGER NOT NULL DEFAULT 0,
    views_max              INTEGER NOT NULL,
    views_remaining        INTEGER NOT NULL,
    failed_attempts        INTEGER NOT NULL DEFAULT 0,
    max_failed_attempts    INTEGER NOT NULL,
    label_enc              BYTEA,
    group_id               TEXT,
    created_at             BIGINT NOT NULL,
    expires_at             BIGINT NOT NULL,
    last_viewed_at         BIGINT
);

CREATE INDEX idx_secrets_expires_at ON secrets (expires_at);
CREATE INDEX idx_secrets_group_id ON secrets (group_id);
CREATE INDEX idx_secrets_creator ON secrets (creator_id);

CREATE TABLE secret_tombstones (
    id                 TEXT PRIMARY KEY,
    org_id             TEXT NOT NULL,
    creator_id         TEXT,
    receipt_token_hash BYTEA NOT NULL,
    status             TEXT NOT NULL,
    views_used         INTEGER NOT NULL DEFAULT 0,
    views_max          INTEGER NOT NULL DEFAULT 0,
    group_id           TEXT,
    created_at         BIGINT NOT NULL,
    closed_at          BIGINT NOT NULL
);

CREATE INDEX idx_tombstones_closed_at ON secret_tombstones (closed_at);

CREATE TABLE audit_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     TEXT NOT NULL,
    secret_id  TEXT,
    user_id    TEXT,
    event      TEXT NOT NULL,
    at         BIGINT NOT NULL,
    ip         TEXT,
    user_agent TEXT,
    detail     TEXT
);

CREATE INDEX idx_audit_secret ON audit_events (secret_id, at);
CREATE INDEX idx_audit_at ON audit_events (at);
CREATE INDEX idx_audit_event ON audit_events (event, at);

CREATE TABLE settings (
    key        TEXT PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE job_locks (
    name        TEXT PRIMARY KEY,
    holder      TEXT NOT NULL,
    acquired_at BIGINT NOT NULL,
    expires_at  BIGINT NOT NULL
);

